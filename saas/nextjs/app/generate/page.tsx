function normalizeExtractedText(text: string) {
  return text
    .replace(/\u0000/g, '')
    .replace(/\r/g, '')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function sanitizeResumeText(text: string) {
  const original = normalizeExtractedText(text);
  if (!original) return '';

  const cleanedLines = original
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((line) => {
      if (/^(page|pagenumber|pdf|docx|doc|word|generated by|created by|copyright|©|all rights reserved)/i.test(line)) {
        return false;
      }
      if (/^(https?:\/\/|www\.)/i.test(line)) {
        return false;
      }
      const letters = line.replace(/[^A-Za-z\u4e00-\u9fa5]/g, '');
      if (letters.length < 2 && line.length > 18) {
        return false;
      }
      const symbolRatio = (line.match(/[^A-Za-z0-9\u4e00-\u9fa5\s]/g) || []).length / Math.max(line.length, 1);
      if (symbolRatio > 0.45 && line.length > 12) {
        return false;
      }
      return true;
    });

  const deduped = Array.from(new Set(cleanedLines));
  const cleaned = deduped.join('\n').replace(/\n{3,}/g, '\n\n').trim();

  return cleaned.length >= 30 ? cleaned : original;
}

function splitSentences(text: string) {
  return text
    .split(/[。！？!?\n]+/)
    .map((item) => item.trim())
    .filter(Boolean);
}

function extractName(text: string, lines: string[]) {
  const firstLine = lines[0] || '';
  if (firstLine.includes('|')) {
    return firstLine.split('|')[0].trim();
  }

  const candidate = firstLine.match(/^[A-Za-z\u4e00-\u9fa5·\s]{2,20}$/);
  if (candidate) {
    return candidate[0].trim();
  }

  return '我';
}

function extractRole(text: string) {
  const roleMatch = text.match(/(高级前端工程师|前端工程师|全栈工程师|产品经理|产品设计师|设计师|运营经理|市场经理|数据分析师|研发工程师|技术负责人|创始人|工程师|产品|运营|设计|开发|研究)/);
  if (roleMatch) return roleMatch[1];
  return '创作者';
}

function extractCompany(text: string) {
  const companyMatch = text.match(/([A-Za-z0-9\u4e00-\u9fa5·\-]+(?:科技|集团|公司|实验室|团队|平台|工作室|有限公司))/);
  return companyMatch?.[1] || '';
}

