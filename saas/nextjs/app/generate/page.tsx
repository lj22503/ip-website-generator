function extractEducation(lines: string[]) {
  return lines.filter((line) => /(大学|学校|本科|硕士|博士|学历|教育)/.test(line)).slice(0, 2);
}

function extractProjects(text: string) {
  return splitSentences(text)
    .filter((sentence) => /(项目|主导|负责|落地|上线|优化|迭代|搭建|重构|交付|设计|开发|推动|实现)/.test(sentence))
    .slice(0, 3);
}

function extractAchievements(text: string) {
  return splitSentences(text)
    .filter((sentence) => /(\d+%|百分之|增长|提升|降低|覆盖|获|荣获|发布|完成|达成|拿下|斩获|显著)/.test(sentence))
    .slice(0, 3);
}

function inferMbti(text: string, role: string) {
  const lowerText = text.toLowerCase();
  if (/(沟通|客户|市场|运营|销售|产品)/.test(lowerText)) return 'ENFP';
  if (/(数据|架构|系统|工程|技术|算法|分析|前端|后端|研发)/.test(lowerText)) return 'INTJ';
  if (/(设计|创意|体验|用户|视觉|ui|ux)/.test(lowerText)) return 'INFP';
  if (/(管理|执行|领导|目标|结果|运营|增长)/.test(lowerText)) return 'ESTJ';
  if (role.includes('设计') || role.includes('产品')) return 'ENFP';
  return 'INTJ';
}

function buildProfileData(resumeText: string, analysis?: AnalysisResult | null): ProfileData {
  const normalized = normalizeExtractedText(resumeText);
  const lines = normalized
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
  const text = normalized.replace(/\s+/g, ' ');

  const name = extractName(text, lines);
  const role = extractRole(text);
  const company = extractCompany(text);
  const skillsFromText = extractSkills(text);
  const educationLines = extractEducation(lines);
  const projects = extractProjects(text);
  const achievements = extractAchievements(text);

  const skillSource = analysis?.dimensions.find((dim) => dim.label.includes('技能') || dim.label.includes('核心'))?.text || '';
  const parsedSkills = skillSource
    .split(/[，、,\n]/)
    .map((item) => item.trim())
    .filter(Boolean)
    .slice(0, 8);

  const skills = skillsFromText.length > 0 ? skillsFromText : parsedSkills;
  const summary = analysis?.short_story || [role, company, projects[0]].filter(Boolean).join(' · ');

  return {
    name,
    role,
    company,
    skills,
    education: educationLines,
    projects,
    achievements,
    values: /用户|价值|成长|原则|诚信|目标/.test(text)
      ? ['目标感', '成长意识', '价值判断']
      : ['执行力', '目标意识', '可持续思维'],
    direction: /产品|运营|增长|市场|数据|架构|系统|技术|AI/.test(text)
      ? ['产品增长', '技术架构', '数据能力']
      : ['职业深耕', '能力扩展'],
    summary,
  };
}

